        /// <summary>Every event of the table.</summary>
        public static IEnumerable<string> Events => Sounds.Keys;

        /// <summary>The generated files the table uses (each once).</summary>
        public static IEnumerable<string> Files()
        {
            var seen = new HashSet<string>();
            foreach (var s in Sounds.Values)
                if (seen.Add(s.File)) yield return s.File;
        }

        /// <summary>
        /// The file and the final pitch of an event played at <paramref name="pitch"/> (the caller's own change, e.g. the rising stars).
        /// False for an unknown event (silence).
        /// </summary>
        public static bool TryResolve(string evt, float pitch, out string file, out float finalPitch)
        {
            file = null;
            finalPitch = pitch;
            if (string.IsNullOrEmpty(evt) || !Sounds.TryGetValue(evt, out var sound)) return false;
            file = sound.File;
            finalPitch = pitch * sound.Pitch;
            return true;
        }

        /// <summary>The win jingle of a game (<c>GameInfo.Id</c>); unknown games: the Plumber one.</summary>
        public static string WinFor(string gameId) =>
            gameId == "trafficjam" ? AudioEvents.TrafficWin : gameId == "penguin" ? AudioEvents.PenguinWin : AudioEvents.PlumberWin;

        /// <summary>
        /// The music of a screen: "" = Home (also the screens of no game), otherwise the game's own (its Story and its Challenge alike).
        /// </summary>
        public static string MusicFor(string gameId)
        {
            switch (gameId)
            {
                case "plumber": return "Music_Plumber";
                case "trafficjam": return "Music_TrafficJam";
                case "penguin": return "Music_Penguin";
                default: return MusicHome;
            }
        }
