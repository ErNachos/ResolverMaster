        public Color icon = Hex(0x3C4250);
        public Color badgeText = Hex(0x5E5470);
        /// <summary>Text outline of titles and of labels on colored buttons (SDF outline of TextMeshPro).</summary>
        public Color outline = Hex(0x1C1726);
